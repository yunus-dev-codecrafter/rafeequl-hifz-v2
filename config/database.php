<?php
declare(strict_types=1);

/**
 * Rafeequl Hifz - PDO Database Connection
 *
 * Configuration is loaded from, in order:
 *   1. config/database.local.php  (ignored by git; preferred)
 *   2. DB_HOST / DB_PORT / DB_NAME / DB_USER / DB_PASS environment variables
 *   3. local development defaults (127.0.0.1 / root / no password)
 *
 * APP_TIMEZONE controls the calendar day used by tasks and rollover counting.
 * It defaults to Africa/Lagos.
 */

@ini_set('display_errors', '0');
@ini_set('log_errors', '1');
error_reporting(E_ALL);

$rhConfig = [];
$rhLocalConfig = __DIR__ . '/database.local.php';
if (is_file($rhLocalConfig)) {
    $loaded = require $rhLocalConfig;
    if (is_array($loaded)) {
        $rhConfig = $loaded;
    }
}

$rhEnv = static function (string $key, string $default = ''): string {
    $value = getenv($key);
    if ($value === false || $value === '') {
        $value = $_SERVER[$key] ?? $_ENV[$key] ?? $default;
    }
    return ($value === false || $value === '') ? $default : (string) $value;
};

$host = (string) ($rhConfig['host'] ?? $rhEnv('DB_HOST', '127.0.0.1'));
$port = (string) ($rhConfig['port'] ?? $rhEnv('DB_PORT', '3306'));
$name = (string) ($rhConfig['name'] ?? $rhEnv('DB_NAME', 'rafeequl_hifz'));
$user = (string) ($rhConfig['user'] ?? $rhEnv('DB_USER', 'root'));
$pass = (string) ($rhConfig['pass'] ?? $rhEnv('DB_PASS', ''));
$timezone = (string) ($rhConfig['timezone'] ?? $rhEnv('APP_TIMEZONE', 'Africa/Lagos'));

if (!in_array($timezone, timezone_identifiers_list(), true)) {
    $timezone = 'Africa/Lagos';
}
date_default_timezone_set($timezone);

if (!defined('RH_APP_TIMEZONE')) {
    define('RH_APP_TIMEZONE', $timezone);
}

if (!defined('RH_FATAL_HANDLER_REGISTERED')) {
    define('RH_FATAL_HANDLER_REGISTERED', true);

    register_shutdown_function(static function (): void {
        $error = error_get_last();
        if (!$error) {
            return;
        }
        $fatalTypes = [E_ERROR, E_PARSE, E_CORE_ERROR, E_COMPILE_ERROR, E_USER_ERROR];
        if (!in_array($error['type'], $fatalTypes, true)) {
            return;
        }
        error_log(sprintf(
            '[RafeequlHifz Fatal] %s in %s:%d',
            $error['message'],
            $error['file'],
            $error['line']
        ));
    });
}

$dsn = sprintf(
    'mysql:host=%s;port=%s;dbname=%s;charset=utf8mb4',
    $host,
    $port,
    $name
);

$options = [
    PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    PDO::ATTR_EMULATE_PREPARES   => false,
    PDO::ATTR_STRINGIFY_FETCHES  => false,
    PDO::ATTR_TIMEOUT            => 10,
    PDO::ATTR_PERSISTENT         => false,
];

// Keep lock waits short so a shared-hosting request fails fast instead of
// hanging until OpenResty returns a 502. MYSQL_ATTR_INIT_COMMAND is only
// available when pdo_mysql is loaded.
if (defined('PDO::MYSQL_ATTR_INIT_COMMAND')) {
    // Align MySQL's NOW()/CURDATE() with APP_TIMEZONE, and keep lock waits
    // short so a shared-hosting request fails fast instead of hanging until
    // OpenResty returns a 502. The offset is generated by PHP, so it follows
    // daylight-saving changes for the configured zone.
    $options[PDO::MYSQL_ATTR_INIT_COMMAND] =
        "SET SESSION innodb_lock_wait_timeout = 10, time_zone = '" . date('P') . "'";
}

try {
    $pdo = new PDO($dsn, $user, $pass, $options);
} catch (PDOException $e) {
    error_log('[DB Connection Failed] ' . $e->getMessage());

    http_response_code(503);
    $wantsJson = (strpos((string) ($_SERVER['REQUEST_URI'] ?? ''), '/api/') !== false)
        || (stripos((string) ($_SERVER['HTTP_ACCEPT'] ?? ''), 'application/json') !== false);

    if ($wantsJson) {
        header('Content-Type: application/json; charset=utf-8');
        echo json_encode(
            ['success' => false, 'error' => 'Database is not available. Please try again shortly.'],
            JSON_UNESCAPED_UNICODE
        );
        exit;
    }

    header('Content-Type: text/html; charset=utf-8');
    echo '<!doctype html><html lang="ar" dir="rtl"><meta charset="utf-8">'
        . '<title>رفيق الحفظ — الإعداد مطلوب</title>'
        . '<body style="font-family:system-ui,sans-serif;max-width:640px;margin:3rem auto;padding:0 1rem;line-height:1.8">'
        . '<h1>الإعداد مطلوب</h1>'
        . '<p>تعذر الاتصال بقاعدة البيانات. إذا كنت تُثبّت التطبيق لأول مرة، افتح '
        . '<a href="setup.php">setup.php</a> لإكمال الإعداد.</p>'
        . '<p>إن كان التطبيق مثبتاً بالفعل، راجع إعدادات قاعدة البيانات في '
        . '<code>config/database.local.php</code>.</p>'
        . '</body></html>';
    exit;
}
