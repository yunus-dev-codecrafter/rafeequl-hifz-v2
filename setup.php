function rh_h($value): string
{
    return htmlspecialchars((string) $value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

function rh_setup_csrf(): string
{
    if (empty($_SESSION['rh_setup_csrf'])) {
        $_SESSION['rh_setup_csrf'] = bin2hex(random_bytes(24));
    }
    return $_SESSION['rh_setup_csrf'];
}

function rh_setup_pdo(array $cfg): PDO
{
    $dsn = sprintf(
        'mysql:host=%s;port=%s;dbname=%s;charset=utf8mb4',
        (string) $cfg['host'],
        (string) ($cfg['port'] ?? '3306'),
        (string) $cfg['name']
    );
    $options = [
        PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES   => false,
        PDO::ATTR_TIMEOUT            => 10,
        PDO::ATTR_PERSISTENT         => false,
    ];
    if (defined('PDO::MYSQL_ATTR_INIT_COMMAND')) {
        $options[PDO::MYSQL_ATTR_INIT_COMMAND] = 'SET SESSION innodb_lock_wait_timeout = 10';
    }
    return new PDO($dsn, (string) $cfg['user'], (string) ($cfg['pass'] ?? ''), $options);
}

function rh_setup_config_code(array $cfg): string
{
    return "<?php\n"
        . "declare(strict_types=1);\n\n"
        . "// Generated by setup.php. Keep this file private.\n"
        . "return " . var_export([
            'host'     => (string) $cfg['host'],
            'port'     => (string) ($cfg['port'] ?? '3306'),
            'name'     => (string) $cfg['name'],
            'user'     => (string) $cfg['user'],
            'pass'     => (string) ($cfg['pass'] ?? ''),
            'timezone' => (string) ($cfg['timezone'] ?? 'Africa/Lagos'),
        ], true) . ";\n";
}

function rh_setup_write_config(array $cfg): bool
{
    $code = rh_setup_config_code($cfg);
    $ok = @file_put_contents(RH_SETUP_CONFIG, $code, LOCK_EX) !== false;
    if ($ok) {
        @chmod(RH_SETUP_CONFIG, 0640);
    }
    return $ok;
}

function rh_setup_schema_statements(string $sql): array
{
    $lines = preg_split('/\R/', $sql) ?: [];
    $clean = [];
    foreach ($lines as $line) {
        $trim = trim($line);
        if ($trim === '' || str_starts_with($trim, '--') || str_starts_with($trim, '#')) {
            continue;
        }
        $clean[] = $line;
    }
    $joined = implode("\n", $clean);
    $parts = preg_split('/;\s*(?:\r?\n|$)/', $joined) ?: [];
    $statements = [];
    foreach ($parts as $part) {
        $part = trim($part);
        if ($part !== '') {
            $statements[] = $part;
        }
    }
    return $statements;
}

function rh_setup_import_schema(PDO $pdo): int
{
    $sqlFile = __DIR__ . '/config/schema.sql';
    $sql = @file_get_contents($sqlFile);
    if ($sql === false) {
        throw new RuntimeException('config/schema.sql is missing or unreadable.');
    }
    $count = 0;
    foreach (rh_setup_schema_statements($sql) as $statement) {
        $pdo->exec($statement);
        $count++;
    }
    return $count;
}

function rh_setup_seed_pages(PDO $pdo): int
{
    $jsonFile = __DIR__ . '/api/data/madinah_pages.json';
    $json = @file_get_contents($jsonFile);
    if ($json === false) {
        throw new RuntimeException('api/data/madinah_pages.json is missing or unreadable.');
    }
    $pages = json_decode($json, true);
    if (!is_array($pages) || count($pages) !== 604) {
        throw new RuntimeException('The Madinah page dataset must contain exactly 604 pages.');
    }

    $sql = 'INSERT INTO `madinah_pages_meta`
                (`page_number`, `juz_number`, `hizb_number`, `rub_el_hizb`, `start_surah_id`, `start_ayah_id`)
            VALUES (:page_number, :juz_number, :hizb_number, :rub_el_hizb, :start_surah_id, :start_ayah_id)
            ON DUPLICATE KEY UPDATE
                `juz_number`     = VALUES(`juz_number`),
                `hizb_number`    = VALUES(`hizb_number`),
                `rub_el_hizb`    = VALUES(`rub_el_hizb`),
                `start_surah_id` = VALUES(`start_surah_id`),
                `start_ayah_id`  = VALUES(`start_ayah_id`)';
    $pdo->beginTransaction();
    try {
        $stmt = $pdo->prepare($sql);
        foreach ($pages as $row) {
            $stmt->execute([
                ':page_number'    => (int) $row['page_number'],
                ':juz_number'     => (int) $row['juz_number'],
                ':hizb_number'    => (int) $row['hizb_number'],
                ':rub_el_hizb'    => (int) $row['rub_el_hizb'],
                ':start_surah_id' => (int) $row['start_surah_id'],
                ':start_ayah_id'  => (int) $row['start_ayah_id'],
            ]);
        }
        $pdo->commit();
    } catch (Throwable $t) {
        if ($pdo->inTransaction()) {
            $pdo->rollBack();
        }
        throw $t;
    }
    return (int) $pdo->query('SELECT COUNT(*) FROM `madinah_pages_meta`')->fetchColumn();
}

function rh_setup_create_admin(PDO $pdo, string $email, string $name, string $password, bool $mustChange = true): int
{
    $hash = password_hash($password, PASSWORD_DEFAULT);
    if ($hash === false) {
        throw new RuntimeException('Could not hash the administrator password.');
    }

    $stmt = $pdo->prepare('SELECT `id` FROM `users` WHERE `email` = :e LIMIT 1');
    $stmt->execute([':e' => $email]);
    $existingId = $stmt->fetchColumn();

    if ($existingId !== false && $existingId !== null) {
        $stmt = $pdo->prepare(
            'UPDATE `users`
             SET `name` = :n,
                 `password_hash` = :h,
                 `user_type` = \'COMPLETE\',
                 `role` = \'SUPER_ADMIN\',
                 `status` = \'ACTIVE\',
                 `status_reason` = NULL,
                 `suspended_at` = NULL,
                 `must_change_password` = :m
             WHERE `id` = :id'
        );
        $stmt->execute([
            ':n'  => $name,
            ':h'  => $hash,
            ':m'  => $mustChange ? 1 : 0,
            ':id' => (int) $existingId,
        ]);
        return (int) $existingId;
    }

    $stmt = $pdo->prepare(
        'INSERT INTO `users`
            (`name`, `email`, `password_hash`, `user_type`, `role`, `status`,
             `current_hifz_page`, `daily_murajaah_target_pages`, `murajaah_days`,
             `rabt_extra_pages`, `last_tikrar_page`, `must_change_password`)
         VALUES
            (:n, :e, :h, \'COMPLETE\', \'SUPER_ADMIN\', \'ACTIVE\',
             0, 100, 6, 0, 0, :m)'
    );
    $stmt->execute([
        ':n' => $name,
        ':e' => $email,
        ':h' => $hash,
        ':m' => $mustChange ? 1 : 0,
    ]);
    return (int) $pdo->lastInsertId();
}

function rh_setup_counts(PDO $pdo): array
{
    $out = ['users' => 0, 'pages' => 0, 'tasks' => 0];
    foreach (['users', 'madinah_pages_meta', 'daily_task_logs'] as $table) {
        try {
            $out[$table === 'madinah_pages_meta' ? 'pages' : ($table === 'daily_task_logs' ? 'tasks' : 'users')]
                = (int) $pdo->query('SELECT COUNT(*) FROM `' . $table . '`')->fetchColumn();
        } catch (Throwable $t) {
            // Table does not exist yet.
        }
    }
    return $out;
}

function rh_setup_lock(): bool
{
    $ok = @file_put_contents(
        RH_SETUP_LOCK,
        'Installed: ' . date('c') . PHP_EOL,
        LOCK_EX
    ) !== false;
    @unlink(RH_SETUP_ENABLE);
    return $ok;
}

