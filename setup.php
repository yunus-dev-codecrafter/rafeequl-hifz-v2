if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!hash_equals($csrf, (string) ($_POST['csrf'] ?? ''))) {
        $errors[] = 'انتهت صلاحية النموذج. أعد تحميل الصفحة وحاول مرة أخرى.';
    } else {
        $action = (string) ($_POST['action'] ?? '');

        if ($action === 'save_db') {
            $newConfig = [
                'host'     => trim((string) ($_POST['host'] ?? '')),
                'port'     => trim((string) ($_POST['port'] ?? '3306')),
                'name'     => trim((string) ($_POST['name'] ?? '')),
                'user'     => trim((string) ($_POST['user'] ?? '')),
                'pass'     => (string) ($_POST['pass'] ?? ''),
                'timezone' => trim((string) ($_POST['timezone'] ?? 'Africa/Lagos')),
            ];
            if ($newConfig['host'] === '' || $newConfig['name'] === '' || $newConfig['user'] === '') {
                $errors[] = 'اسم المضيف واسم قاعدة البيانات واسم المستخدم مطلوبة.';
            }
            if (!ctype_digit($newConfig['port']) || (int) $newConfig['port'] < 1 || (int) $newConfig['port'] > 65535) {
                $errors[] = 'منفذ قاعدة البيانات غير صالح.';
            }
            if (!in_array($newConfig['timezone'], timezone_identifiers_list(), true)) {
                $errors[] = 'المنطقة الزمنية غير صالحة.';
            }
            if (!$errors) {
                try {
                    $testPdo = rh_setup_pdo($newConfig);
                    $testPdo->query('SELECT 1');
                    if (!rh_setup_write_config($newConfig)) {
                        $errors[] = 'تعذر كتابة config/database.local.php. أنشئ الملف يدوياً باستخدام الكود أدناه.';
                        $resultHtml = '<p class="warn">انسخ هذا المحتوى إلى <code>config/database.local.php</code> ثم أعد تحميل الصفحة:</p>'
                            . '<textarea readonly rows="12" style="width:100%;font-family:monospace;direction:ltr">'
                            . rh_h(rh_setup_config_code($newConfig))
                            . '</textarea>';
                    } else {
                        header('Location: setup.php?db=1');
                        exit;
                    }
                } catch (Throwable $t) {
                    error_log('[Setup DB] ' . $t->getMessage());
                    $errors[] = 'تعذر الاتصال بقاعدة البيانات. راجع المضيف واسم القاعدة والمستخدم وكلمة المرور.';
                }
            }
            $config = $newConfig;
            // Do not expose the install/upgrade actions until the config file
            // was actually written. A failed write must be fixed first.
            $configLoaded = false;
        }
    }
}

if ($configLoaded && !$pdo) {
    try {
        $pdo = rh_setup_pdo($config);
        $pdo->query('SELECT 1');
    } catch (Throwable $t) {
        error_log('[Setup DB] ' . $t->getMessage());
        $dbError = 'تعذر الاتصال بقاعدة البيانات المحفوظة. راجع الإعدادات أدناه.';
        $pdo = null;
