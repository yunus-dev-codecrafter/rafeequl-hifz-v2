if ($_SERVER['REQUEST_METHOD'] === 'POST' && $action !== '' && $action !== 'save_db' && !$errors) {
    if (!$pdo) {
        $errors[] = 'قاعدة البيانات غير متاحة. احفظ إعدادات الاتصال أولاً.';
    } else {
        try {
            if ($action === 'install' || $action === 'upgrade') {
                $email = trim((string) ($_POST['admin_email'] ?? ''));
                $name = trim((string) ($_POST['admin_name'] ?? ''));
                $password = (string) ($_POST['admin_password'] ?? '');
                $wantsAdmin = $email !== '' || $password !== '';

                if ($action === 'install' && $counts['users'] > 0) {
                    throw new RuntimeException('توجد حسابات مستخدمين بالفعل. استخدم خيار «ترقية قاعدة البيانات» بدلاً من التثبيت الجديد.');
                }
                if ($action === 'install' && (!$wantsAdmin || $email === '' || $password === '')) {
                    throw new RuntimeException('التثبيت الجديد يحتاج بريد المشرف وكلمة مروره.');
                }
                if ($wantsAdmin) {
                    if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
                        throw new RuntimeException('بريد المشرف غير صالح.');
                    }
                    if (strlen($password) < 10) {
                        throw new RuntimeException('كلمة مرور المشرف يجب أن تكون 10 أحرف على الأقل.');
                    }
                    if ($name === '') {
                        $name = 'المشرف العام';
                    }
                }

                $log = static function (string $message) use (&$notices): void {
                    $notices[] = $message;
                };

                if ($action === 'install') {
                    $notices[] = 'إنشاء الجداول من config/schema.sql...';
                    $statementCount = rh_setup_import_schema($pdo);
                    $notices[] = 'تم تنفيذ ' . $statementCount . ' أمر إنشاء.';
