                    'الترقية: %d عموداً، %d فهرساً، %d جدولاً.',
                    $stats['columns_added'],
                    $stats['indexes_added'],
                    $stats['tables_created']
                );

                $pageCount = rh_setup_seed_pages($pdo);
                $notices[] = 'بيانات صفحات المصحف: ' . $pageCount . ' صفحة.';

                if ($wantsAdmin) {
                    $adminId = rh_setup_create_admin($pdo, $email, $name, $password, true);
                    $notices[] = 'حساب المشرف جاهز (#' . $adminId . '). سيُطلب تغيير كلمة المرور عند أول دخول.';
                }

                $lockOk = rh_setup_lock();
                $resultHtml = '<div class="ok"><strong>تم الإعداد بنجاح.</strong></div>'
                    . '<p>افتح <a href="web/index.html">التطبيق</a> وسجّل الدخول.</p>'
                    . ($lockOk
                        ? '<p>تم إنشاء <code>config/installed.lock</code> وتعطيل المثبّت.</p>'
                        : '<p class="warn">تم الإعداد، لكن تعذر إنشاء ملف القفل. احذف <code>setup.php</code> فوراً.</p>')
                    . '<p class="warn"><strong>احذف <code>setup.php</code> من الخادم الآن.</strong></p>';
            } elseif ($action === 'seed_pages') {
                $pageCount = rh_setup_seed_pages($pdo);
                $notices[] = 'بيانات صفحات المصحف: ' . $pageCount . ' صفحة.';
                $lockOk = rh_setup_lock();
                $resultHtml = '<div class="ok"><strong>تم تحديث بيانات الصفحات.</strong></div>'
                    . ($lockOk ? '<p>تم تعطيل المثبّت.</p>' : '<p class="warn">احذف setup.php فوراً.</p>');
            } elseif ($action === 'admin') {
                $email = trim((string) ($_POST['admin_email'] ?? ''));
                $name = trim((string) ($_POST['admin_name'] ?? ''));
                $password = (string) ($_POST['admin_password'] ?? '');
                if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
                    throw new RuntimeException('بريد المشرف غير صالح.');
                }
                if (strlen($password) < 10) {
                    throw new RuntimeException('كلمة مرور المشرف يجب أن تكون 10 أحرف على الأقل.');
                }
                if ($name === '') {
                    $name = 'المشرف العام';
                }
                $adminId = rh_setup_create_admin($pdo, $email, $name, $password, true);
                $notices[] = 'حساب المشرف جاهز (#' . $adminId . ').';
                $lockOk = rh_setup_lock();
                $resultHtml = '<div class="ok"><strong>تم إنشاء/تحديث حساب المشرف.</strong></div>'
                    . '<p>سجّل الدخول من <a href="web/index.html">صفحة الدخول</a>؛ ستُطلب كلمة مرور جديدة عند أول دخول.</p>'
                    . ($lockOk ? '<p>تم تعطيل المثبّت.</p>' : '<p class="warn">احذف setup.php فوراً.</p>');
            } else {
                throw new RuntimeException('إجراء غير معروف.');
            }
        } catch (Throwable $t) {
            error_log('[Setup Action] ' . $t->getMessage());
            $errors[] = $t->getMessage();
        }
    }
}

